param([ValidateSet('api','runner')][string]$Component='api',[switch]$VerifyOnly)
$ErrorActionPreference='Stop'
Add-Type -AssemblyName System.Security
$repoRoot=Split-Path $PSScriptRoot -Parent
$releaseRoot=Join-Path $repoRoot '.runtime/release'
$manifestPath=Join-Path $releaseRoot 'manifest.ps1'
$signature=Get-AuthenticodeSignature -LiteralPath $manifestPath
if($signature.Status -ne 'Valid' -or $signature.SignerCertificate.Thumbprint -ne '4F8341A74D16077AE1849DC8B8CAC99F22606754' -or -not $signature.TimeStamperCertificate){throw 'A valid, timestamped publisher signature is required.'}
# Signed data only: the manifest is never executed.
$filesLine=[IO.File]::ReadAllLines($manifestPath) | Where-Object { $_.StartsWith('# files=') }
if(@($filesLine).Count -ne 1){throw 'Missing release file hashes.'}
$files=$filesLine.Substring(8) | ConvertFrom-Json
foreach($entry in $files.PSObject.Properties){
 $filePath=Join-Path $releaseRoot $entry.Name
 if((Get-FileHash -LiteralPath $filePath -Algorithm SHA256).Hash -ne $entry.Value){throw "Changed release file: $($entry.Name)"}
}
$binary=Join-Path $releaseRoot "$Component.exe"
$binarySignature=Get-AuthenticodeSignature -LiteralPath $binary
if($binarySignature.Status -ne 'Valid' -or $binarySignature.SignerCertificate.Thumbprint -ne '4F8341A74D16077AE1849DC8B8CAC99F22606754' -or -not $binarySignature.TimeStamperCertificate){throw 'The service binary must also be signed.'}
if($VerifyOnly){'Signed service and all release files verified.';exit 0}
$bytes=[Security.Cryptography.ProtectedData]::Unprotect([IO.File]::ReadAllBytes((Join-Path $repoRoot '.runtime/private/settings.dpapi')),$null,[Security.Cryptography.DataProtectionScope]::CurrentUser)
try{
 $settings=[Text.Encoding]::UTF8.GetString($bytes) | ConvertFrom-Json
 foreach($entry in $settings.PSObject.Properties){[Environment]::SetEnvironmentVariable($entry.Name,[string]$entry.Value,'Process')}
}finally{[Array]::Clear($bytes,0,$bytes.Length)}
Remove-Item Env:DATABASE_PASSWORD -ErrorAction SilentlyContinue
$env:PORT='8187'
$env:DATABASE_MIGRATIONS='verify'
$env:TRUST_PROXY_CLIENT_IP='cloudflare'
$env:WEB_ROOT=Join-Path $releaseRoot 'web'
$env:PATH="$releaseRoot;$env:PATH"
$env:RUST_LOG='info,sqlx=warn'
Set-Location -LiteralPath $releaseRoot
$logRoot=Join-Path $repoRoot '.runtime/logs'
New-Item -ItemType Directory -Path $logRoot -Force | Out-Null
$ErrorActionPreference='Continue'
& $binary 1>> (Join-Path $logRoot "$Component.stdout.log") 2>> (Join-Path $logRoot "$Component.stderr.log")
exit $LASTEXITCODE

